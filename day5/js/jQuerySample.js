// ---------------------------------------------------------------------------
// イベント
// 直接イベントを設定する方法とonメソッドを使って設定する方法の2種類
// ---------------------------------------------------------------------------
// 直接的にイベントを設定する方法
// ※簡潔な設定方法。eventNameと記載しましたが、正確にはメソッドです。
$("セレクター").eventName(function () {
    // イベントが発生したときの処理
});

// onメソッドでイベントを設定する方法
// ※onメソッドを使うと要素に対して複数イベントの設定ができたりする
$("セレクター").on("eventName", function () {
    // イベントが発生したときの処理
});

