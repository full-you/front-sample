// ---------------------------------------------------------------------------
// jQueryを使ったAjaxの実装サンプル
// ---------------------------------------------------------------------------
// ★success / error を使うパターン
function successError() {
    $.ajax({
        url: "https://sample.com/xxx", // 通信先APIのURL
        method: "GET", // GET/POSTなど通信方法
        dataType: "json", //APIから返ってくるデータ形式。この形式のデータをjsオブジェクトに自動変換

        success: function (response) { // 通信成功時の処理。引数のresponseはAPIからのレスポンス(変数名は任意設定)
            $("#name").text(response.name);
            $("#email").text(response.email);
        },

        error: function () { // 通信失敗時の処理
            console.log("通信失敗");
        },

        complete: completeFunc // 必ず実行される処理（javaでいうとfinally的な存在）
    });
}

$("#btn1").click(function () {
    successError();
});

// completeにて実行される関数
function completeFunc() {
    console.log("必ず実行される");
}

// ★done / fail を使うパターン
function doneFail() {
    $.ajax({
        url: "https://sample.com/xxx", // 通信先APIのURL
        method: "GET", // GET/POSTなど通信方法
        dataType: "json", //返ってくるデータ形式。この形式のデータをjsオブジェクトに自動変換
    })
        .done(function (response) { // 通信成功時の処理。引数のresponseはAPIからのレスポンス(変数名は任意設定)
            $("#name").text(response.name);
            $("#email").text(response.email);
        })
        .fail(function () { // 通信失敗時の処理
            console.log("通信失敗");
        })
        .always(alwaysFunc); // 必ず実行される処理（javaでいうとfinally的な存在）
}

$("#btn2").click(function () {
    doneFail();
});

// alwaysにて実行される関数
function alwaysFunc(){
    console.log("必ず実行される");
}